#!/usr/bin/env node
// Builds the scenario table and the record index in evals/skills/README.md
// from evals/skills/records/*.md, so a pull request that adds a case touches
// its own record file and regenerates the README instead of hand-editing a
// shared table.
//
//   node evals/skills/build-index.mjs           rewrite the README
//   node evals/skills/build-index.mjs --check   exit 1 if the README is stale
//
// A record is a Markdown file whose first `# ` heading is its title. Its
// optional frontmatter lists the scenario-table rows it owns:
//
//   ---
//   scenarios:
//     - request: Build a Finnomena request tracker
//       observe: At 1440×900 the list and the add-request action are visible on load
//   ---
//
// Values run to the end of the line. Quote one as a JSON string when it would
// not be a plain YAML scalar (it contains ": " or " #", or starts with a quote,
// backtick or other indicator). Rows are ordered by record file name, then by
// their order in the file, so records added in parallel land apart.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = fileURLToPath(new URL('.', import.meta.url));
export const README = join(here, 'README.md');
export const RECORDS = join(here, 'records');

const MARKERS = {
  scenarios: ['<!-- BEGIN scenarios: generated by build-index.mjs from the records; edit those, then rerun -->', '<!-- END scenarios -->'],
  records: ['<!-- BEGIN records: generated by build-index.mjs -->', '<!-- END records -->'],
};

const PLAIN = /^(?![-?:,[\]{}#&*!|>'"%@`\s])(?!.*(?:: | #))(?!.*:$).+$/;

export function formatValue(value) {
  return PLAIN.test(value) ? value : JSON.stringify(value);
}

function parseValue(raw, where) {
  const value = raw.trim();
  if (!value) throw new Error(`${where}: empty value`);
  if (!value.startsWith('"')) return value;
  try {
    return JSON.parse(value);
  } catch {
    throw new Error(`${where}: quoted value is not a JSON string`);
  }
}

// { slug, title, scenarios: [{ request, observe }] } from one record's text.
export function parseRecord(text, file) {
  const slug = file.replace(/^.*\//, '').replace(/\.md$/, '');
  const scenarios = [];
  let body = text;
  if (text.startsWith('---\n')) {
    const end = text.indexOf('\n---\n', 3);
    if (end < 0) throw new Error(`${file}: frontmatter has no closing ---`);
    const lines = text.slice(4, end).split('\n');
    body = text.slice(end + 5);
    if (lines[0] !== 'scenarios:') throw new Error(`${file}:2: expected "scenarios:"`);
    for (let index = 1; index < lines.length; index += 2) {
      const request = lines[index].match(/^ {2}- request:(.*)$/);
      const observe = lines[index + 1]?.match(/^ {4}observe:(.*)$/);
      if (!request || !observe) throw new Error(`${file}:${index + 2}: expected "  - request:" then "    observe:"`);
      scenarios.push({
        request: parseValue(request[1], `${file}:${index + 2}`),
        observe: parseValue(observe[1], `${file}:${index + 3}`),
      });
    }
  }
  const title = body.match(/^# (.+)$/m)?.[1];
  if (!title) throw new Error(`${file}: no "# " title heading`);
  return { slug, title, scenarios };
}

export function readRecords(directory = RECORDS) {
  return readdirSync(directory).filter(name => name.endsWith('.md')).sort()
    .map(name => parseRecord(readFileSync(join(directory, name), 'utf8'), `records/${name}`));
}

const cell = text => text.replace(/\|/g, '\\|');
const link = record => `[${record.title}](records/${record.slug}.md)`;

function replaceBetween(readme, [begin, end], content) {
  const start = readme.indexOf(begin);
  const stop = readme.indexOf(end);
  if (start < 0 || stop < start) throw new Error(`README is missing the markers ${begin} … ${end}`);
  return `${readme.slice(0, start + begin.length)}\n${content}\n${readme.slice(stop)}`;
}

export function buildReadme(readme, records) {
  const rows = records.flatMap(record => record.scenarios.map(({ request, observe }) =>
    `| ${cell(request)} | ${cell(observe)} | ${link(record)} |`));
  const table = ['| Request/context | Observe | Record |', '| --- | --- | --- |', ...rows].join('\n');
  const index = records.map(record => `- ${link(record)}`).join('\n');
  return replaceBetween(replaceBetween(readme, MARKERS.scenarios, table), MARKERS.records, index);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const current = readFileSync(README, 'utf8');
  const built = buildReadme(current, readRecords());
  if (process.argv.includes('--check')) {
    if (built !== current) {
      console.error('evals/skills/README.md is stale; run node evals/skills/build-index.mjs');
      process.exit(1);
    }
  } else if (built !== current) {
    writeFileSync(README, built);
    console.log('Rewrote evals/skills/README.md');
  }
}
