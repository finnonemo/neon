import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { README, RECORDS, buildReadme, formatValue, parseRecord, readRecords } from './build-index.mjs';
import { checkMarkdownLinks } from '../../scripts/lib/markdown-links.mjs';

// The scenario table and record index are generated from records/*.md (#85).

test('the README matches its records; run node evals/skills/build-index.mjs if not', () => {
  const readme = readFileSync(README, 'utf8');
  assert.equal(readme, buildReadme(readme, readRecords()), 'evals/skills/README.md is stale; run node evals/skills/build-index.mjs');
});

test('links in the README and every record resolve', async () => {
  await checkMarkdownLinks(README);
  for (const name of readdirSync(RECORDS)) await checkMarkdownLinks(join(RECORDS, name));
});

test('frontmatter values round-trip, quoting only what plain YAML cannot hold', () => {
  const values = ['Build a Finnomena request tracker', 'Follow-up: "ให้ดู finnomena มากขึ้น"', '`Review this screenshot; do not edit`', 'Open: Look and fix', 'A | B'];
  const text = ['---', 'scenarios:', ...values.flatMap(value => [`  - request: ${formatValue(value)}`, `    observe: ${formatValue(value)}`]), '---', '', '# Case', ''].join('\n');
  const record = parseRecord(text, 'records/case.md');
  assert.deepEqual(record.scenarios.map(row => row.request), values);
  assert.equal(formatValue(values[0]), values[0]);
  assert.match(formatValue(values[1]), /^"/);
  assert.match(buildReadme('<!-- BEGIN scenarios: generated by build-index.mjs from the records; edit those, then rerun -->\n<!-- END scenarios -->\n<!-- BEGIN records: generated by build-index.mjs -->\n<!-- END records -->\n', [record]), /\| A \\\| B \|/);
});

test('rejects a record with malformed frontmatter or no title', () => {
  assert.throws(() => parseRecord('---\nscenarios:\n  - request: x\n---\n\n# Case\n', 'records/case.md'), /records\/case.md:3/);
  assert.throws(() => parseRecord('---\nscenarios:\n  - request: x\n    observe: "unclosed\n---\n\n# Case\n', 'records/case.md'), /not a JSON string/);
  assert.throws(() => parseRecord('No title\n', 'records/case.md'), /no "# " title/);
});

test('rows follow record file names, so parallel additions land apart', () => {
  const records = readRecords();
  assert.deepEqual(records.map(record => record.slug), records.map(record => record.slug).sort());
});
